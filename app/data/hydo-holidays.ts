/**
 * hydo 공휴일 오버레이 — 앱에 **박혀 있는 표를 덮어쓰는 패치**다.
 *
 * 앱은 공휴일 표를 자기 안에 들고 있다(`App/Shared/KoreanHolidays.swift`, 스크립트가
 * 굽는다). 여기 있는 것은 그 표의 **예외**뿐이다:
 *
 *   1. 임시공휴일 지정      — 표에 없는 날짜를 더한다
 *   2. 지정 철회 · 날짜 변경 — 옛 날짜를 `name: null` 로 지우고 새 날짜를 더한다
 *   3. 표의 오타 정정       — 심사 없이 고칠 수 있는 **유일한 길**이다
 *
 * ## 왜 필요한가
 *
 * 임시공휴일은 예고 없이 생긴다. 2025년 1월 27일은 **1월 14일 국무회의**에서
 * 확정됐다 — 13일 전이다. 앱 심사(1~3일)에 사용자 업데이트 도달(수 주)을 더하면
 * 절대 못 따라가고, 네이티브 앱에는 OTA 업데이트도 없다.
 *
 * ## 올리는 방법
 *
 *   1. 아래 배열에 항목을 하나 추가한다
 *   2. `npm run dev` 후 `curl -s localhost:3000/api/hydo/holidays | jq` 로 확인한다
 *   3. `main` 에 push 한다 → Vercel 자동 배포 → 최대 5분 뒤 반영
 *      (앱은 하루에 한 번 받아 가므로 사용자에게 닿는 데는 최대 하루가 더 걸린다)
 *
 * ⚠️ **표에 반영된 뒤에도 항목을 지우지 말 것.** 새 빌드의 표에 들어갔더라도 옛
 * 버전이 아직 돌고 있다. 패치는 멱등이라 중복 적용돼도 결과가 같다.
 * 그래서 공지와 달리 `minVersion`/`maxVersion` 이 없다 — 넣으면 CDN 캐시만 쪼개진다.
 *
 * ⚠️ **`date` 에 시각이나 오프셋을 붙이지 말 것.** 이건 순간이 아니라 달력의 하루다.
 * `2026-10-05T00:00:00+09:00` 처럼 쓰면 라우트가 그 항목을 통째로 거른다.
 */

export type HydoHolidayPatch = {
  /** `YYYY-MM-DD`. 시각도 오프셋도 붙이지 않는다. */
  date: string;

  /**
   * 공휴일 이름. 앱 달력 칸에 그대로 그려진다.
   *
   * **`null` 이면 "이날은 공휴일이 아니다"** — 지정 철회나 표의 오타 정정에 쓴다.
   *
   * ⚠️ 6자를 넘기지 말 것. 위젯 칸이 44pt 라 넘치면 그냥 잘린다
   * (`KoreanHolidays.longestNameLength` 와 한 쌍이다).
   */
  name: string | null;

  /** 왜 넣었는지. **앱으로 나가지 않는다** — 1년 뒤 이 줄을 보는 사람을 위한 것이다. */
  note?: string;
};

