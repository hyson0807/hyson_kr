/**
 * hydo 앱 공지사항 — 여기가 정본이다.
 *
 * ## 공지를 새로 올리는 방법
 *
 *   1. 아래 `hydoNotices` 배열 **맨 위**에 항목을 하나 추가한다
 *   2. `npm run dev` 후 `curl -s localhost:3000/api/hydo/notices | jq` 로 확인한다
 *   3. `main` 에 push 한다 → Vercel 자동 배포 → 최대 5분 뒤 앱에 반영
 *
 * 앱 심사가 필요 없다. 네이티브 앱에는 OTA 업데이트가 없어서 코드는 한 글자만
 * 고쳐도 새 빌드 + 새 심사지만, **내용만 바뀌는 것**은 이렇게 서버에서 내려준다.
 *
 * ## 앱이 이 값을 어떻게 쓰는가
 *
 * 앱은 안 본 공지 중 **가장 최신 한 건만** 모달로 띄우고, 나머지는
 * 설정 › 공지사항 목록에 남긴다. 한 번 닫은 공지는 다시 뜨지 않는다.
 *
 * ⚠️ 서식이 없다. 본문은 평문으로 그려지므로 마크다운(`**굵게**`)이나 HTML 을
 * 쓰면 기호가 그대로 글자로 보인다. 줄바꿈은 `\n` 만 먹는다.
 */

export type HydoNotice = {
  /**
   * 앱이 "이 공지를 봤다"를 기록하는 키.
   *
   * ⚠️ 한 번 배포한 뒤에는 **절대 바꾸지 말 것** — 바꾸면 이미 닫은 사람에게
   * 모달이 다시 뜬다. 오타를 고칠 때도 id 는 그대로 두고 본문만 고친다.
   * 형식은 `YYYY-MM-DD-슬러그`.
   */
  id: string;

  /** 모달 제목. 한 줄로 끝나는 길이가 좋다. */
  title: string;

  /** 본문. 평문이고 줄바꿈은 `\n`. */
  body: string;

  /**
   * 이 시각부터 노출한다. KST 오프셋(`+09:00`)을 붙여 써도 되고,
   * 라우트가 UTC 로 정규화해서 내보낸다.
   */
  publishedAt: string;

  /**
   * 이 시각부터 숨긴다. 없으면 영영 남는다.
   *
   * ⚠️ **대부분의 공지에는 넣을 것.** 안 넣으면 반년 뒤에 앱을 처음 설치한
   * 사람에게도 지난 점검 안내가 모달로 뜬다.
   */
  expiresAt?: string;

  /** 이 버전 **이상**에만 노출한다. 예: `'1.1.0'` */
  minVersion?: string;

  /** 이 버전 **미만**에만 노출한다. 구버전 사용자 안내용. */
  maxVersion?: string;
};

/**
 * 최신이 위로 오게 쌓는다 (순서는 라우트가 다시 정렬하므로 강제는 아니다).
 *
 * 작성 예시:
 *
 *   {
 *     id: '2026-08-05-launch',
 *     title: 'hydo 가 App Store 에 출시됐습니다',
 *     body: '이제 잠금화면에서 이번 달 일정을 바로 확인할 수 있습니다.\n설정 › 단축어 자동화 설정에서 시작해 보세요.',
 *     publishedAt: '2026-08-05T09:00:00+09:00',
 *     expiresAt: '2026-09-05T09:00:00+09:00',
 *   },
 */
export const hydoNotices: HydoNotice[] = [];
